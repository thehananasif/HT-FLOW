import type { RunnerConfig } from './core';

/**
 * Deploy-time bundle: one `runner.js` = a header with the runner's config (strategy id, inputs,
 * instrument, feed, risk) + the prebuilt runner core (SDK + built-in strategies + paper engine +
 * Node entry, see apps/desktop/runnerBundle.ts). The bundle id is the SHA-256 of the file, so
 * the app can tell whether the VPS runs the current build.
 */

export interface RunnerBundle {
  source: string;
  sha256: string;
  bytes: number;
}

/** JSON safe inside a JS source file (no `</script>`, U+2028/2029 escaped). */
export function jsLiteral(v: unknown): string {
  return JSON.stringify(v)
    .replace(/</g, '\\u003c')
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029');
}

export function bundleHeader(cfg: RunnerConfig): string {
  return [
    '// HT Flow headless runner — generated by the desktop app. Paper trading only.',
    `// Runner ${cfg.runnerId}: ${cfg.strategyName.replace(/[\r\n\u2028\u2029]/g, ' ')} on ${cfg.feed.exchange} ${cfg.feed.symbol}`,
    `globalThis.__HTFLOW_RUNNER_CONFIG__ = ${jsLiteral(cfg)};`,
    '',
  ].join('\n');
}

export async function sha256Hex(text: string): Promise<string> {
  const data = new TextEncoder().encode(text);
  const h = await crypto.subtle.digest('SHA-256', data);
  return [...new Uint8Array(h)].map((b) => b.toString(16).padStart(2, '0')).join('');
}

/** `core` is CommonJS; the header only defines a global that the core reads when it runs. */
export async function buildRunnerBundle(core: string, cfg: RunnerConfig): Promise<RunnerBundle> {
  if (!core.trim()) throw new Error('The runner core is empty');
  const source = bundleHeader(cfg) + core;
  return {
    source,
    sha256: await sha256Hex(source),
    bytes: new TextEncoder().encode(source).length,
  };
}

/** Loads the prebuilt core (a lazily built chunk; never part of the main bundle). */
export async function loadRunnerCore(): Promise<string> {
  const m = await import('virtual:htflow-vps-runner');
  return m.default;
}
