import type { IndicatorCategory, RawInputs } from '@htflow/indicator-sdk';

/** One entry of the Appendix B catalog. `impl` names the implementing indicator (with optional preset inputs). */
export interface CatalogEntry {
  key: string;
  name: string;
  category: IndicatorCategory;
  group?: string;
  impl?: string;
  inputs?: RawInputs;
  /** Why it is pending (blocked data source, later phase…). */
  note?: string;
}

const slug = (s: string) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

type Row = [name: string, impl?: string, inputs?: RawInputs, note?: string];

function rows(category: IndicatorCategory, group: string | undefined, list: Row[]): CatalogEntry[] {
  return list.map(([name, impl, inputs, note]) => ({
    key: `${category}:${slug(name)}`,
    name,
    category,
    group,
    impl,
    inputs,
    note,
  }));
}

